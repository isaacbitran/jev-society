import argparse, os, glob, json
from .engine import run
ap = argparse.ArgumentParser(prog="python -m jevsociety", description="Run a semantic-culture society and record it for the viewer.")
ap.add_argument("--n", type=int, default=400, help="population (square number)")
ap.add_argument("--ticks", type=int, default=60)
ap.add_argument("--k", type=int, default=5, help="beliefs per agent")
ap.add_argument("--openness", type=float, default=1.0, help="multiplier on adoption probability")
ap.add_argument("--rewire", type=float, default=0.0, help="small-world rewiring probability (0 = pure grid)")
ap.add_argument("--rule", choices=["jev", "axelrod"], default="jev")
ap.add_argument("--seed", type=int, default=0)
ap.add_argument("--snap-every", type=int, default=2)
ap.add_argument("--budget", type=float, default=2.0, help="stop when this run has spent this many USD")
ap.add_argument("--name", default=None)
ap.add_argument("--pool", default="politics", help="belief pool: politics | life")
ap.add_argument("--drop-gap", type=float, default=1.0, help="scale the measured side gap in drop-rule coherence: 1 raw, 0 neutral, -1 reversed, 2 doubled")
ap.add_argument("--lean-fix", type=float, default=0.0, help="0 raw Jev, 1 subtract measured side lean, 2 reverse it, -1 double it")
a = ap.parse_args()
name = a.name or f"{a.rule}_n{a.n}_open{a.openness}_rw{a.rewire}_s{a.seed}"
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(here, "viewer", "runs", name + ".js")
rec = run(a.n, a.ticks, a.k, a.openness, a.rewire, a.rule, a.seed, a.snap_every, out, a.budget, pool=a.pool, lean_fix=a.lean_fix, drop_gap=a.drop_gap)
names = sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob(os.path.join(here, "viewer", "runs", "*.js")) if not p.endswith("index.js"))
open(os.path.join(here, "viewer", "runs", "index.js"), "w").write("window.RUN_NAMES=" + json.dumps(names) + ";\n")
print("wrote", out, "cost USD", rec["cost_usd"])
